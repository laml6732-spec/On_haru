import { chromium } from 'playwright-core';
import fs from 'node:fs';
import path from 'node:path';

const base=process.env.ONHARU_URL||'http://127.0.0.1:8080/legacy/';
const out=path.resolve('test-results/scripture-memory');
fs.mkdirSync(out,{recursive:true});
const exe=process.env.CHROME_PATH||undefined;
const browser=await chromium.launch({headless:true,...(exe?{executablePath:exe}:{}),args:['--no-sandbox','--disable-dev-shm-usage']});
const results=[];
const check=(label,condition)=>{if(!condition)throw new Error(label);};
async function sample(width,theme){
 const context=await browser.newContext({viewport:{width,height:844},colorScheme:theme,timezoneId:'Pacific/Honolulu',isMobile:width<600,hasTouch:width<600,serviceWorkers:'block'});
 const page=await context.newPage();page.setDefaultTimeout(10000);
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.route('**/legacy/nlt?*',async route=>route.fulfill({status:200,contentType:'text/html',body:'<verse_export vn="4"><p><span class="vn">4</span>Sample first verse <verse_export vn="5"><span class="vn">5</span>Sample second verse</verse_export></p></verse_export>'}));
 try{
   await page.goto(base,{waitUntil:'domcontentloaded'});
   await page.locator('#tutorialChooseEn').click();
   await page.locator('#welcomeSkip').click();
   await page.locator('.tabs [data-page="capture"]').waitFor({state:'visible'});
   const nav=await page.locator('.tabs button[data-page]').allTextContents();
   const norm=nav.map(x=>x.trim());
   check('Five live tabs',norm.length===5);
   check('Live tab order',JSON.stringify(norm)==JSON.stringify(['Write','Check-in','Plan','Focus','Review']));
   await page.locator('#sm-write-cue').waitFor({state:'visible'});
   check('Correct placement',await page.locator('#sm-write-cue').evaluate(e=>e.previousElementSibling?.id==='qc-v2'));
   const from=await page.evaluate(()=>localStorage.getItem('kona.legacy.v1.dayframe'));
   await page.screenshot({path:path.join(out,width+'-'+theme+'-write.png'),animations:'disabled'});
   await page.locator('#sm-write-cue').click();
   await page.locator('#sm-overlay').waitFor({state:'visible'});
   check('Focus selected after Write',await page.locator('.tabs [data-page="focus"]').evaluate(e=>e.classList.contains('active')));
   await page.locator('.sm-verse').first().waitFor({state:'visible'});
   const verseBodies=await page.locator('.sm-verse').allTextContents();
   check('Nested provider verses separated',verseBodies.length===2&&verseBodies[0].includes('Sample first verse')&&!verseBodies[0].includes('Sample second verse')&&verseBodies[1].includes('Sample second verse'));
   check('Verse number hierarchy preserved',JSON.stringify(await page.locator('.sm-verse-number').allTextContents())===JSON.stringify(['4','5']));
   const disclosure=page.locator('.sm-direct-reading');
   check('Direct-reading disclosure available for supplied sample',await disclosure.count()===1);
   check('Direct-reading collapsed initially',!(await disclosure.evaluate(x=>x.open)));
   check('Direct-reading text hidden while collapsed',!(await page.locator('.sm-direct-body').isVisible()));
   await disclosure.locator('summary').click();
   check('Direct-reading expands on tap',await disclosure.evaluate(x=>x.open));
   check('Direct-reading shows two corresponding verses',await page.locator('.sm-direct-verse').count()===2);
   check('Direct-reading text visible',await page.locator('.sm-direct-body').isVisible());
   await disclosure.locator('summary').click();
   check('Direct-reading collapses again',!(await disclosure.evaluate(x=>x.open)));
   check('Direct-reading text hidden again',!(await page.locator('.sm-direct-body').isVisible()));
   await disclosure.locator('summary').click();
   await page.screenshot({path:path.join(out,width+'-'+theme+'-expanded.png'),animations:'disabled'});
   await page.screenshot({path:path.join(out,width+'-'+theme+'-read.png'),animations:'disabled'});
   check('Reflection is default',await page.getByText('Pause with the passage').isVisible());
   check('Memorization is optional',await page.getByRole('button',{name:'Memorize (optional)'}).isVisible());
   check('No recall checkpoint on reading view',await page.getByRole('button',{name:'Check recall'}).count()===0);
   await page.getByRole('button',{name:'Mark as read'}).click();
   await page.getByRole('button',{name:'Save for later'}).click();
   let state=await page.evaluate(()=>JSON.parse(localStorage.getItem('kona.scripture-memory.v1')));
   check('Reading date persisted',!!state.passages['1-corinthians-13-4-5'].read_at);
   check('Bookmark persisted',state.passages['1-corinthians-13-4-5'].saved_for_later===true);
   check('Reading did not force memorization',state.passages['1-corinthians-13-4-5'].status==='learning');
   check('No journal data overwritten on reading',await page.evaluate(()=>localStorage.getItem('kona.legacy.v1.dayframe'))===from);
   await page.getByRole('button',{name:'Memorize (optional)'}).click();
   check('Hide verse on recall',await page.locator('.sm-verse').count()===0);
   await page.getByRole('button',{name:'Check recall'}).click();
   await page.getByRole('button',{name:'I remembered'}).click();
   state=await page.evaluate(()=>JSON.parse(localStorage.getItem('kona.scripture-memory.v1')));
   check('Optional recall persisted',state.passages['1-corinthians-13-4-5'].attempts.length===1);
   await page.getByRole('button',{name:'Mark as memorized'}).click();
   state=await page.evaluate(()=>JSON.parse(localStorage.getItem('kona.scripture-memory.v1')));
   check('Optional memorization persisted',state.passages['1-corinthians-13-4-5'].status==='memorized');
   check('Reading/bookmark preserved by old recall state',!!state.passages['1-corinthians-13-4-5'].read_at&&state.passages['1-corinthians-13-4-5'].saved_for_later);
   await page.getByRole('button',{name:'Back to reading'}).click();
   await page.getByRole('button',{name:'Write a reflection'}).click();
   await page.locator('#sm-overlay').waitFor({state:'hidden'});
   check('Returned to Write',await page.locator('.tabs [data-page="capture"]').evaluate(e=>e.classList.contains('active')));
   check('Reference prefilled in note title',await page.locator('#qc-note-title').inputValue()==='1 Corinthians 13:4-5');
   check('No note auto-submitted',await page.locator('#qc-text').inputValue()==='');
   check('Scripture tag selected',await page.locator('.kona-capture-tags [data-tag="meaning_scripture"]').getAttribute('aria-pressed')==='true');
   // Existing user drafts are never replaced by a scripture handoff.
   await page.locator('#qc-text').fill('Existing user draft');
   await page.locator('#sm-write-cue').click();
   await page.locator('#sm-overlay').waitFor({state:'visible'});
   await page.getByRole('button',{name:'Write a reflection'}).click();
   check('Preserved preexisting user draft',await page.locator('#qc-text').inputValue()==='Existing user draft');
   await page.locator('.tabs [data-page="records"]').click();
   await page.locator('#rev-archive').click();
   await page.locator('#sm-library-entry').waitFor({state:'visible'});
   await page.locator('#sm-library-entry').click();
   check('Catalog 100 rows',await page.locator('.sm-list-row').count()===100);
   await page.screenshot({path:path.join(out,width+'-'+theme+'-library.png'),animations:'disabled'});
   await page.getByRole('button',{name:'Read',exact:true}).click();
   check('Read filter includes one passage',await page.locator('.sm-list-row').count()===1);
   await page.getByRole('button',{name:'Saved',exact:true}).click();
   check('Saved filter includes one passage',await page.locator('.sm-list-row').count()===1);
   await page.getByRole('button',{name:'All',exact:true}).click();
   await page.locator('.sm-search').fill('John');
   check('Search filters',await page.locator('.sm-list-row').count()>0&&await page.locator('.sm-list-row').count()<100);
   const dims=await page.evaluate(()=>({scrollWidth:document.documentElement.scrollWidth,clientWidth:document.documentElement.clientWidth}));
   check('No viewport overflow',dims.scrollWidth<=dims.clientWidth+2);
   check('No JS errors',errors.length===0);
   results.push({width,theme,pass:true,nav:norm,errors});
 }catch(e){results.push({width,theme,pass:false,error:String(e),errors});throw e}
 finally{await context.close()}
}
try{for(const [width,theme] of [[320,'light'],[390,'dark'],[1024,'light']])await sample(width,theme)}
finally{await browser.close();fs.writeFileSync(path.join(out,'results.json'),JSON.stringify(results,null,2));}
console.log(JSON.stringify(results,null,2));
if(results.some(x=>!x.pass))process.exit(1);
